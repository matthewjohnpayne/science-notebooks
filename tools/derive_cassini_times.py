#!/usr/bin/env python3
"""Approximate times of the Cassini range measurements used by Holman & Payne (2016), for the
notebook notebooks/cassini_planet9.

HP16 do not tabulate their data. Their Figure 1 (top panel, "Unperturbed Residuals") plots every
range residual against time. We download the arXiv source (1604.03180), find the blue points in
that panel, and turn the number of blue pixels in each column into a distribution of measurement
times; overlapping points make this approximate. N_POINTS times are then placed at evenly spaced
quantiles of that distribution. Only the times are used, not the residual values.

    python tools/derive_cassini_times.py       # writes notebooks/cassini_planet9/data/range_times.csv
    python tools/derive_cassini_times.py 1604.03180.tar.gz   # or from a downloaded copy of the source
"""
import io
import pathlib
import sys
import tarfile

import numpy as np
import requests
from PIL import Image

OUT = pathlib.Path(__file__).resolve().parents[1] / "notebooks" / "cassini_planet9" / "data" / "range_times.csv"
N_POINTS = 190            # from HP16 App. B: Delta sigma = 10% <-> Delta chi^2 ~ 40 implies N ~ 190
# Pixel geometry of COMPARISON.png's top panel: the frame spans x = 208-539 and y = 21-135;
# the year ticks put 2004.0 at the left edge and 2014.0 at x ~ 508, i.e. 30.1 px per year.
X0, X1, Y0, Y1, PX_PER_YEAR = 209, 539, 22, 135, 30.1

if len(sys.argv) > 1:
    src = open(sys.argv[1], "rb").read()
else:
    r = requests.get("https://arxiv.org/e-print/1604.03180", timeout=120)
    r.raise_for_status()
    src = r.content
with tarfile.open(fileobj=io.BytesIO(src)) as tar:
    png = tar.extractfile("COMPARISON.png").read()
im = np.asarray(Image.open(io.BytesIO(png)).convert("RGB")).astype(int)[Y0:Y1, X0:X1]
blue = (im[..., 2] > 180) & (im[..., 0] < 90) & (im[..., 1] < 90)
blue[:30, :190] = False                              # the legend box
col = blue.sum(0).astype(float)
yr = 2004 + (np.arange(blue.shape[1]) + 0.5) / PX_PER_YEAR
cdf = np.cumsum(col) / col.sum()
times = np.interp((np.arange(N_POINTS) + 0.5) / N_POINTS, cdf, yr)
jd = 2453005.5 + (times - 2004.0) * 365.25
OUT.parent.mkdir(parents=True, exist_ok=True)
with open(OUT, "w") as f:
    f.write("# Approximate Cassini range-measurement times (JD, TDB) derived from Holman & Payne (2016) Fig. 1;\n")
    f.write(f"# {N_POINTS} quantiles of the blue-point distribution. Generated by tools/derive_cassini_times.py.\n")
    f.write("jd\n")
    for v in jd:
        f.write(f"{v:.3f}\n")
print(f"Wrote {OUT}: {N_POINTS} times, {times[0]:.2f} to {times[-1]:.2f} (about {col.sum() / 9:.0f} visible points)")
